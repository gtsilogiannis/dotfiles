-- Colors generated by matugen into ~/.config/hypr/colors.lua (not tracked).
-- The fallback keeps the session usable if that file is missing or invalid.
local colors = {
    primary         = "rgba(00f5ffcc)",
    tertiary        = "rgba(ff007fcc)",
    outline         = "rgba(8e9099ff)",
    outline_variant = "rgba(24273aaa)",
}
local ok, generated = pcall(function()
    return dofile(os.getenv("HOME") .. "/.config/hypr/colors.lua")
end)
if ok and type(generated) == "table" then
    colors = generated
end

-- Desktop mode, written by ~/.config/quickshell/scripts/mode.sh, which reloads
-- Hyprland after every switch. Browsing: rotating gradient border, translucent
-- windows. Focus: static border, opaque windows, calmer animations.
local mode = "browsing"
pcall(function()
    local file = io.open(os.getenv("HOME") .. "/.local/state/desktop/mode", "r")
    if file then
        if file:read("*l") == "focus" then mode = "focus" end
        file:close()
    end
end)
local focus = mode == "focus"

-- Browsing only: mode.sh opaque (SUPER + BackSpace) turns the glass windows opaque.
-- Every login starts with glass (mode.sh init writes "off").
local opaque = false
if not focus then
    pcall(function()
        local file = io.open(os.getenv("HOME") .. "/.local/state/desktop/opaque", "r")
        if file then
            opaque = file:read("*l") == "on"
            file:close()
        end
    end)
end
local solid = focus or opaque

